_CODE_TO_NAME: Dict[str, str] = dict(DEFAULT_STATION_CODES)
_NAME_TO_CODE: Dict[str, str] = {v: k for k, v in DEFAULT_STATION_CODES.items()}
_NAME_TO_CODE["台北"] = "1000"
_NAME_TO_CODE["台中"] = "3300"
_NAME_TO_CODE["台南"] = "4220"
_NAME_TO_CODE["台東"] = "6000"

def get_stations_path() -> str:
    root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    return os.path.join(root_dir, "stations.json")

def init_stations():
    """初始化並在開 App 時載入與同步字典"""
    global _CODE_TO_NAME, _NAME_TO_CODE
    path = get_stations_path()

    # 1. 優先載入本地 stations.json
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
                for k, v in data.items():
                    if k.isdigit() and len(k) == 4 and not v.isdigit():
                        _CODE_TO_NAME[k] = v
                        _NAME_TO_CODE[v] = k
        except Exception as e:
            print(f"[WARN] 載入 stations.json 失敗: {e}")

    # 2. 開機時在背景嘗試檢查並持久化最新字典
    def _bg_sync():
        try:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(_CODE_TO_NAME, f, ensure_ascii=False, indent=2)
        except Exception:
            pass

    threading.Thread(target=_bg_sync, daemon=True).start()

# 模組載入時立即初始化
init_stations()

def get_station_code(name_or_code: str) -> str:
    """
    獲取標準 4 碼站號 (如 1000, 6180)。
    如果已經是 4 碼站號，直接回傳，0 延遲，不再需要反覆字串轉換。
    """
    val = (name_or_code or "").strip()
    if "-" in val:
        val = val.split("-")[0].strip()
    if val.isdigit() and len(val) == 4:
        return val
    # 若傳入站名，快速查字典
    if val in _NAME_TO_CODE:
        return _NAME_TO_CODE[val]
    # 繁簡台字相容
    norm = val.replace("台", "臺")
    if norm in _NAME_TO_CODE:
        return _NAME_TO_CODE[norm]
    return val

def get_station_name(name_or_code: str) -> str:
    """傳入站號或站名，回傳標準中文名稱 (如 '1000' -> '臺北')"""
    code = get_station_code(name_or_code)
    return _CODE_TO_NAME.get(code, name_or_code)

def get_station_fullname(name_or_code: str) -> str:
    """回傳下拉選單標準格式：1000-臺北"""
    code = get_station_code(name_or_code)
    name = get_station_name(code)
    return f"{code}-{name}"

def get_all_stations() -> List[Dict[str, str]]:
    """回傳按站號排序的全台所有車站清單供 UI 選擇"""
    result = []
    for code in sorted(_CODE_TO_NAME.keys()):
        name = _CODE_TO_NAME[code]
        result.append({
            "code": code,
            "name": name,
            "label": f"{code}-{name}"
        })
    return result

